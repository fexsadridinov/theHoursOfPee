test('a batch of drafts stays in a table and saves together', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Log hours', exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Hours', { exact: true }).fill('0.75')
  await dialog.getByLabel('Notes').fill('Repeated supervision')
  await dialog.getByRole('button', { name: 'Add another', exact: true }).click()
  const table = dialog.getByRole('table', { name: 'Entries to save' })
  await expect(table.getByRole('row')).toHaveCount(3)
  await dialog.getByRole('button', { name: 'Previous day' }).click()
  await dialog.getByLabel('Notes').fill('Adjusted second')
  await expect(dialog.getByRole('button', { name: 'Save 2 entries' })).toBeVisible()
  await table.getByRole('row').nth(1).getByRole('button').first().click()
  await expect(dialog.getByLabel('Notes')).toHaveValue('Repeated supervision')
  await expect(dialog.getByLabel('Hours', { exact: true })).toHaveValue('0.75')
  await dialog.getByRole('button', { name: 'Save 2 entries' }).click()
  await expect(page.getByRole('status')).toContainText('2 entries logged')
  await expect(page.getByText('Repeated supervision')).toBeVisible()
  await expect(page.getByText('Adjusted second')).toBeVisible()
})

