import { test, expect } from '@playwright/test'

const dashboard = 'Your hours at a glance.'

test('logging hours works with nothing but the prefilled defaults', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: dashboard })).toBeVisible()
  await page.getByRole('button', { name: 'Log hours', exact: true }).first().click()
  await page.getByLabel('Hours', { exact: true }).fill('1.5')
  await page.getByLabel('Notes').fill('Playwright private entry')
  await page.getByRole('button', { name: 'Save entry' }).click()
  await expect(page.getByText('Playwright private entry')).toBeVisible()
  await expect(page.getByText('1.5 h').first()).toBeVisible()
})

test('direct, indirect, and supervision hours summon the matching activity dropdown', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Log hours', exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('radio', { name: /Direct hours/ })).toBeVisible()
  const direct = dialog.getByLabel('Direct activity')
  await expect(direct).toBeVisible()
  await expect(direct.locator('option', { hasText: 'Intake Interviewing/Assessment' })).toHaveCount(1)
  await expect(direct.locator('option', { hasText: 'Individual Counseling' })).toHaveCount(1)
  await dialog.getByRole('radio', { name: /Indirect hours/ }).click()
  const indirect = dialog.getByLabel('Indirect activity')
  await expect(indirect.locator('option', { hasText: 'Record Keeping' })).toHaveCount(1)
  await expect(indirect.locator('option', { hasText: 'Administrative Tasks' })).toHaveCount(1)
  await expect(indirect.locator('option', { hasText: 'Supervision' })).toHaveCount(0)
  await dialog.getByRole('radio', { name: /^Supervision/ }).click()
  const supervision = dialog.getByLabel('Supervision', { exact: true })
  await expect(supervision.locator('option', { hasText: 'Individual Supervision' })).toHaveCount(1)
  await expect(supervision.locator('option', { hasText: 'Group Supervision' })).toHaveCount(1)
  await dialog.getByRole('radio', { name: /Indirect hours/ }).click()
  await dialog.getByLabel('Hours', { exact: true }).fill('2')
  await dialog.getByLabel('Notes').fill('Indirect write-up')
  await dialog.getByRole('button', { name: 'Save entry' }).click()
  await expect(page.getByText('Indirect write-up')).toBeVisible()
})
